# ============================================================================
# Purpose:  Designing the 48 to 16 kHz decimator's Kaiser-windowed low-pass and writing its tap table header
# Layer:    NativeBridge.Tools
# Owns:     (script, no public types)
# Depends:  (none)
# ============================================================================

import argparse
import math
from pathlib import Path

import numpy as np

SAMPLE_RATE_HZ = 48000
OUTPUT_PATH = Path(__file__).resolve().parent.parent / "src" / "frontend" / "decimator_taps.h"


def design_r4():
    return "r4", 95, 7800.0, 8.5


def design_f1():
    pass_edge_hz = 7600.0
    stop_edge_hz = 8400.0
    attenuation_db = 60.0
    beta = 0.1102 * (attenuation_db - 8.7)
    delta_omega = 2.0 * math.pi * (stop_edge_hz - pass_edge_hz) / SAMPLE_RATE_HZ
    count = math.ceil((attenuation_db - 7.95) / (2.285 * delta_omega) + 1.0)
    if count % 2 == 0:
        count += 1
    return "f1", count, (pass_edge_hz + stop_edge_hz) / 2.0, beta


DESIGNS = {"r4": design_r4, "f1": design_f1}


def design_taps(count, cutoff_hz, beta):
    ratio = 2.0 * cutoff_hz / SAMPLE_RATE_HZ
    offsets = np.arange(count, dtype=np.float64) - (count - 1) / 2.0
    windowed = ratio * np.sinc(ratio * offsets) * np.kaiser(count, beta)
    return windowed / np.sum(windowed, dtype=np.float64)


def float_literal(value):
    text = format(float(np.float32(value)), ".9g")
    if not any(mark in text for mark in ".en"):
        text += ".0"
    return text + "f"


def render(name, count, cutoff_hz, beta, taps):
    lines = [
        "// ============================================================================",
        "// Purpose:  Decimator low-pass tap table generated by NativeBridge~/tools/design_decimator.py --design " + name,
        "// Layer:    NativeBridge.Frontend",
        "// Owns:     kDecimatorDesign, kDecimatorCutoffHz, kDecimatorKaiserBeta, kDecimatorSampleRateHz, kDecimatorTapCount, kDecimatorTaps (constexpr constants)",
        "// Depends:  (none)",
        "// ============================================================================",
        "",
        "#ifndef VOXR_FRONTEND_DECIMATOR_TAPS_H",
        "#define VOXR_FRONTEND_DECIMATOR_TAPS_H",
        "",
        "namespace voxr {",
        "",
        'constexpr char kDecimatorDesign[] = "' + name + '";',
        "constexpr double kDecimatorCutoffHz = " + repr(float(cutoff_hz)) + ";",
        "constexpr double kDecimatorKaiserBeta = " + repr(float(beta)) + ";",
        "constexpr int kDecimatorSampleRateHz = " + str(SAMPLE_RATE_HZ) + ";",
        "constexpr int kDecimatorTapCount = " + str(count) + ";",
        "",
        "constexpr float kDecimatorTaps[kDecimatorTapCount] = {",
    ]
    lines += ["    " + float_literal(tap) + "," for tap in taps]
    lines += [
        "};",
        "",
        "}",
        "",
        "#endif",
    ]
    return "".join(line + "\r\n" for line in lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--design", choices=sorted(DESIGNS), default="f1")
    args = parser.parse_args()
    name, count, cutoff_hz, beta = DESIGNS[args.design]()
    taps = design_taps(count, cutoff_hz, beta)
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_bytes(render(name, count, cutoff_hz, beta, taps).encode("ascii"))


if __name__ == "__main__":
    main()
